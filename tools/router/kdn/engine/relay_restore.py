"""Repo-controlled Telegram WS init regeneration and transactional rescue state.

Snapshots never provide executable relay init content. Existing owned init bytes
are captured only in process memory for rescue of the same local transaction.
"""
import os
from pathlib import Path
import shlex
import stat

from kdn.common import fsutil
from kdn.engine import config, confvalues, nfqws_process, preflight_xray, snapshot_store, transaction


MARKER = b'# Telegram WS relay of keenetic-discord-nfqws2'
INIT = '/opt/etc/init.d/S99kdn-telegram-ws'
MAX_INIT = 65536

# Fixed repository-controlled counterpart of legacy write_telegram_ws_init.
# No runtime extraction/evaluation of the shell engine or snapshot executables.
BODY = r'''
is_relay() {
  case "$1" in ''|*[!0-9]*) return 1 ;; esac
  tr '\0' ' ' 2>/dev/null < "/proc/$1/cmdline" | grep -Fq -- "$RELAY --listen $LISTEN"
}
relay_pids() {
  for proc in /proc/[0-9]*; do
    comm=""
    read -r comm 2>/dev/null < "$proc/comm" || continue
    case "$comm" in python*) ;; *) continue ;; esac
    pid="${proc#/proc/}"
    is_relay "$pid" && echo "$pid"
  done
}
running() {
  [ -f "$PIDFILE" ] || return 1
  is_relay "$(sed -n '1p' "$PIDFILE" 2>/dev/null)" && return 0
  rm -f "$PIDFILE"
  return 1
}
listening() {
  port_hex="$(printf '%04X' "$PORT")"
  if [ -r /proc/net/tcp ]; then
    awk -v port=":$port_hex" '$4 == "0A" && substr($2, length($2) - 4) == port { found = 1 } END { exit !found }' /proc/net/tcp
  else
    netstat -ltn 2>/dev/null | grep -q "[:.]$PORT "
  fi
}
start() {
  if running; then
    listening && return 0
    stop
  fi
  [ -z "$(relay_pids)" ] || stop
  mkdir -p "$(dirname "$PIDFILE")" "$(dirname "$LOG")"
  # MARK adds two words or none, as in the package's legacy service.
  "$PYTHON" "$RELAY" --listen "$LISTEN" --pidfile "$PIDFILE" --log "$LOG" \
    --cf-domains-file "$CF_DOMAINS" --cf-ips-file "$CF_IPS" ${MARK:+--mark "$MARK"} </dev/null >/dev/null 2>&1 &
  waited=0
  while [ "$waited" -lt 10 ]; do
    sleep 1
    waited=$((waited + 1))
    if running && listening; then
      sleep 1
      if running && listening; then return 0; fi
    fi
  done
  echo "Telegram WS relay did not start or listen on $LISTEN" >&2
  return 1
}
stop() {
  pids="$(relay_pids)"
  if [ -n "$pids" ]; then
    for pid in $pids; do kill "$pid" 2>/dev/null || true; done
    waited=0
    while [ "$waited" -lt 5 ]; do
      alive=""
      for pid in $pids; do is_relay "$pid" && alive="$alive $pid"; done
      [ -n "$alive" ] || break
      sleep 1
      waited=$((waited + 1))
    done
    for pid in $pids; do
      if is_relay "$pid"; then kill -9 "$pid" 2>/dev/null || true; fi
    done
  fi
  rm -f "$PIDFILE"
}
case "$1" in
  start) start ;;
  stop) stop ;;
  restart) stop; start ;;
  status) if running && listening; then echo running; else echo stopped; exit 1; fi ;;
  *) echo "Usage: $0 start|stop|restart|status" >&2; exit 2 ;;
esac
'''


class RelayState:
    __slots__ = ('data', 'mode', 'running')

    def __init__(self, data=None, mode=0o755, running=False):
        self.data, self.mode, self.running = data, mode, running


def _path(ctx):
    return snapshot_store._no_links(config.list_path(INIT, ctx.paths.test_root))


def _owned(path):
    if not path.exists():
        return None
    data = snapshot_store._read(path, MAX_INIT)
    if not data.startswith(b'#!/bin/sh\n') or MARKER not in data.split(b'\n')[:4]:
        # Legacy first marker line ends in '. Generated by', accept that prefix.
        if not data.startswith(b'#!/bin/sh\n') or not any(line.startswith(MARKER) for line in data.split(b'\n')[:4]):
            raise ValueError('Telegram WS init is not project-owned; nothing was changed')
    return data


def _command(ctx, path, verb, *, required=True):
    if verb not in ('start', 'stop', 'restart', 'status'):
        raise ValueError('unsupported relay operation')
    done = nfqws_process.run(['sh', str(path), verb], ctx.environ, timeout=30,
                             output_limit=65536, cwd='/')
    if done.timed_out or done.output_limited or (required and done.returncode):
        raise RuntimeError('Telegram WS relay ' + verb + ' failed')
    return done


def preflight(ctx, routes):
    """No service changes/writes; reject unknown init before any rollback mutation."""
    transaction.guard(ctx, readonly=True)
    _owned(_path(ctx))
    if 'ws' not in routes:
        return
    if not os.path.isfile(ctx.paths.telegram_ws_python) or not os.access(ctx.paths.telegram_ws_python, os.X_OK):
        raise ValueError('Telegram WS Python interpreter is unavailable')
    helper = snapshot_store._read(ctx.paths.telegram_ws_relay, 2 * 1024 * 1024)
    if b'"--mark"' not in helper:
        raise ValueError('Telegram WS helper does not support --mark')
    port = config.telegram_ws_port(ctx.paths, ctx.environ)
    if not port.isascii() or not port.isdecimal() or not 1 <= int(port) <= 65535:
        raise ValueError('invalid Telegram WS listen port')


def _mark(ctx):
    text = confvalues.read_text(ctx.paths.nfqws_conf)
    if confvalues.recorded_deployment_mode(text) == 'standalone-zapret':
        return ''
    request = preflight_xray.XrayRequest(())
    try:
        return preflight_xray.resolve_direct_mark(ctx.paths, request)
    except preflight_xray.XrayCheckError as error:
        raise ValueError('cannot resolve restored Telegram WS direct mark') from error


def render(ctx):
    """Fixed init with quoted canonical paths and mark recalculated after restore."""
    preflight(ctx, ('ws',))
    port = config.telegram_ws_port(ctx.paths, ctx.environ)
    logical = lambda path: config.list_path(path, ctx.paths.test_root)
    values = (
        ('PYTHON', ctx.paths.telegram_ws_python), ('RELAY', ctx.paths.telegram_ws_relay),
        ('PIDFILE', logical('/opt/var/run/kdn-telegram-ws.pid')),
        ('LOG', logical('/opt/var/log/kdn-telegram-ws.log')),
        ('LISTEN', '127.0.0.1:' + port), ('PORT', port),
        ('CF_DOMAINS', str(Path(ctx.paths.state_root) / 'telegram-ws-domains.txt')),
        ('CF_IPS', str(Path(ctx.paths.state_root) / 'telegram-ws-cf-ips.txt')),
        ('MARK', _mark(ctx)),
    )
    if any('\0' in value for _name, value in values):
        raise ValueError('NUL in relay configuration')
    header = '#!/bin/sh\n' + MARKER.decode() + '. Generated by native guarded restore.\n'
    assignments = ''.join(name + '=' + shlex.quote(value) + '\n' for name, value in values)
    return (header + assignments + BODY).encode('utf-8', 'surrogateescape')


def capture(ctx):
    transaction.guard(ctx)
    path = _path(ctx)
    data = _owned(path)
    if data is None:
        return RelayState()
    running = _command(ctx, path, 'status', required=False).returncode == 0
    return RelayState(data, stat.S_IMODE(path.stat().st_mode), running)


def _stop(ctx, path):
    if _owned(path) is not None:
        _command(ctx, path, 'stop')
        if _command(ctx, path, 'status', required=False).returncode == 0:
            raise RuntimeError('Telegram WS relay is still running after stop')


def reconcile(ctx, route):
    transaction.guard(ctx)
    preflight(ctx, (route,))
    path = _path(ctx)
    if route == 'ws':
        # Stop using the previous owned settings before replacing its MARK/port.
        _stop(ctx, path)
        fsutil.atomic_bytes(path, render(ctx), 0o755)
        _command(ctx, path, 'restart')
        _command(ctx, path, 'status')
        ctx.console.out('Telegram WS relay running on 127.0.0.1:' + config.telegram_ws_port(ctx.paths, ctx.environ))
    else:
        _stop(ctx, path)
        path.unlink(missing_ok=True)
        ctx.console.out('Telegram WS relay stopped and removed.')


def restore_init(ctx, saved):
    """Restore same-transaction helper bytes before rescue service reconciliation."""
    transaction.guard(ctx)
    if (not isinstance(saved, RelayState) or not isinstance(saved.running, bool)
            or not isinstance(saved.mode, int) or not 0 <= saved.mode <= 0o777):
        raise ValueError('invalid in-memory relay rescue state')
    path = _path(ctx)
    _stop(ctx, path)
    if saved.data is None:
        path.unlink(missing_ok=True)
    else:
        if not isinstance(saved.data, bytes) or not any(line.startswith(MARKER) for line in saved.data.split(b'\n')[:4]):
            raise ValueError('invalid in-memory relay init')
        fsutil.atomic_bytes(path, saved.data, saved.mode)


def restore_saved(ctx, saved):
    restore_init(ctx, saved)
    if saved.data is not None and saved.running:
        path = _path(ctx)
        _command(ctx, path, 'restart')
        _command(ctx, path, 'status')
